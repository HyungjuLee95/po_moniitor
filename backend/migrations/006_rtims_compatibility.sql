begin;

-- Local/offline RTIMS compatibility schema.
-- The live application still reads the existing Oracle RTIMS schema.
-- PostgreSQL identifiers intentionally use lowercase snake_case.
create schema if not exists rtims;

create table if not exists rtims.pm_intf_group (
    group_id bigint generated by default as identity primary key,
    group_nm varchar(60) not null,
    use_yn char(1) not null,
    create_dtm timestamptz default now(),
    modified_dtm timestamptz default now(),
    description varchar(300),
    style_id bigint,
    modify_user varchar(20)
);

create table if not exists rtims.pm_interface (
    intf_id bigint generated by default as identity primary key,
    intf_nm varchar(300) not null,
    status char(1) not null,
    create_dtm timestamptz default now(),
    modified_dtm timestamptz default now(),
    intf_level char(1) not null default '1',
    ob_base_mapping char(1) default 'N',
    payload_yn char(1) default 'N',
    itgc_yn char(1) default 'N',
    cloud_intf_type varchar(20) default 'NONE',
    response_time bigint,
    description varchar(1000),
    group_id bigint,
    modify_user varchar(20),
    mng_intf_id varchar(30)
);

create index if not exists ix_rtims_pm_interface_group
    on rtims.pm_interface (group_id, intf_id);

create table if not exists rtims.mon_intf_map (
    intf_map_id bigint generated by default as identity primary key,
    ob_ns varchar(255) not null,
    ob_intf_nm varchar(100) not null,
    ob_system varchar(60) not null,
    ib_ns varchar(255) not null,
    ib_intf_nm varchar(100) not null,
    ib_system varchar(60) not null,
    server_id varchar(10) not null,
    first_ts timestamptz,
    last_ts timestamptz,
    pattern_id bigint not null,
    intf_id bigint not null,
    constraint uq_rtims_mon_intf_map_route unique (
        ob_ns, ob_intf_nm, ob_system, ib_ns, ib_intf_nm, ib_system, server_id
    )
);

create index if not exists ix_rtims_mon_intf_map_intf
    on rtims.mon_intf_map (intf_id);

create table if not exists rtims.mon_msg_log (
    log_id bigint generated by default as identity primary key,
    msg_id varchar(64),
    msg_status varchar(3),
    intf_map_id bigint,
    type char(1),
    client_id varchar(3),
    req_msg_size integer,
    res_msg_size integer,
    req_start_dtm timestamptz,
    req_end_dtm timestamptz,
    res_start_dtm timestamptz,
    res_end_dtm timestamptz,
    req_elapsed_sec numeric(15,3),
    prov_elapsed_sec numeric(15,3),
    res_elapsed_sec numeric(15,3),
    server_id varchar(10),
    closed char(1) not null default 'N',
    host_id varchar(80),
    res_msg_id varchar(64),
    persist_until_ts timestamptz
);

create index if not exists ix_rtims_mon_msg_log_msg
    on rtims.mon_msg_log (msg_id);
create index if not exists ix_rtims_mon_msg_log_res_msg
    on rtims.mon_msg_log (res_msg_id);
create index if not exists ix_rtims_mon_msg_log_start
    on rtims.mon_msg_log (req_start_dtm);
create index if not exists ix_rtims_mon_msg_log_start_map
    on rtims.mon_msg_log (req_start_dtm, intf_map_id);
create index if not exists ix_rtims_mon_msg_log_persist
    on rtims.mon_msg_log (persist_until_ts);

create table if not exists rtims.mon_daily_statistics (
    intf_map_id bigint not null,
    ymdd varchar(8) not null,
    hour smallint not null,
    msg_status varchar(3) not null,
    count bigint default 0,
    volume bigint default 0,
    latency numeric(15,3) default 0,
    max_latency numeric(15,3) default 0,
    primary key (intf_map_id, ymdd, hour, msg_status),
    constraint ck_rtims_daily_hour check (hour between 0 and 23)
);

-- Provisional minimum contract: the supplied legacy material does not include
-- the original MON_DAILY_CLOSE_STAT DDL. These are the only columns currently
-- consumed by RtimsRepository.system_statistics().
create table if not exists rtims.mon_daily_close_stat (
    intf_map_id bigint not null,
    ymdd varchar(8) not null,
    hour smallint not null,
    count bigint default 0,
    primary key (intf_map_id, ymdd, hour),
    constraint ck_rtims_close_hour check (hour between 0 and 23)
);

create table if not exists rtims.mon_channinfo (
    server_id varchar(10) not null,
    chann_id varchar(32) not null,
    chann_nm varchar(60) not null,
    business_service varchar(60),
    state char(10),
    chann_type varchar(20),
    last_mdfy_dtm timestamptz,
    direction char(1) not null,
    automation varchar(20),
    activation_state varchar(20),
    connection_url text,
    db_user varchar(100),
    period varchar(50),
    destination varchar(200),
    qos varchar(50),
    last_err_since bigint,
    short_txt varchar(800),
    last_proc_msgs varchar(2000),
    select_query text,
    persist_until_ts timestamptz,
    primary key (server_id, chann_id)
);

create table if not exists rtims.mon_resource (
    resource_id bigint generated by default as identity primary key,
    type varchar(10),
    resourcenm varchar(100),
    description varchar(100)
);

create table if not exists rtims.mon_res_usage (
    server_id varchar(10) not null,
    resource_id bigint not null,
    node varchar(24) not null,
    ymdd varchar(8) not null,
    minute_day integer not null,
    sum_usage numeric(15,3) default 0,
    max_usage numeric(15,3) default 0,
    min_usage numeric(15,3) default 0,
    recent_usage numeric(15,3) default 0,
    max_limit numeric(15,3) default 0,
    usage_cnt integer default 0,
    persist_until_ts timestamptz,
    primary key (server_id, resource_id, node, ymdd, minute_day),
    constraint ck_rtims_minute_day check (minute_day between 0 and 1439)
);

create table if not exists rtims.mon_ae_queue (
    server_id varchar(10) not null,
    servernode varchar(20) not null,
    queuename varchar(50) not null,
    conname varchar(50) not null,
    started varchar(1) not null,
    num_entries bigint,
    threads_assigned integer,
    threads_working integer,
    max_thread integer,
    persist_until_ts timestamptz,
    primary key (server_id, servernode, queuename, conname)
);

create table if not exists rtims.mon_q_status (
    server_id varchar(24) not null,
    client_id varchar(3) not null,
    direction char(1) not null,
    msg_count integer,
    severity char(1) not null,
    create_dtm varchar(14),
    persist_until_ts timestamptz,
    primary key (server_id, client_id, direction, severity)
);

create table if not exists rtims.sys_err_cate (
    err_cate_id bigint generated by default as identity primary key,
    err_cate_nm varchar(50) not null,
    err_cate_desc varchar(200)
);

create table if not exists rtims.sys_err_code (
    err_code_id bigint generated by default as identity primary key,
    err_code varchar(45),
    err_level char(1),
    err_desc varchar(200),
    err_cate_id bigint not null
);

create table if not exists rtims.mon_err_hist (
    err_log_id bigint generated by default as identity primary key,
    ref_msg_id varchar(32),
    ref_server_id varchar(20),
    ref_client_id varchar(3),
    ref_intf_map_id bigint,
    err_msg varchar(1536),
    error_level char(1),
    err_dtm timestamptz,
    err_state char(1) default 'O',
    err_proc_msg varchar(4000),
    err_code_id bigint,
    user_id varchar(24),
    persist_until_ts timestamptz
);

create index if not exists ix_rtims_mon_err_hist_ref_msg
    on rtims.mon_err_hist (ref_msg_id);

commit;
